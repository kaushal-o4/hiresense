"""Deterministic parts of the interview report, computed from stored scores and observable answer data.

Nothing here is generated by the AI or inferred from appearance: dimension scores are averages of the per-answer
criterion scores, and "response indicators" are counts and timings of what the candidate did (words, time,
speaking pace, filler words). Technical knowledge is reported separately from communication, so imperfect English
does not show up as a lack of knowledge.
"""
from __future__ import annotations

import re

from . import ai, interviewers

TECHNICAL_TYPES = {"technical", "project"}
FILLERS = re.compile(r"\b(um+|uh+|erm+|hmm+|you know|i mean|sort of|kind of)\b", re.IGNORECASE)
INDICATOR_LIMITS = (
    "These indicators only describe observable behaviour (answer length, timing, speaking pace, filler words). They "
    "are not a measure of confidence, personality or ability. Time to answer includes thinking, speaking and "
    "reviewing the transcript. Speaking rate counts only the time you were actually talking (pauses excluded), "
    "and speech recognition may drop or add filler words.")


def _near(a: str, b: str) -> bool:
    """Same topic in other words ('Specific middleware implementation details' ~ '... for security')."""
    from difflib import SequenceMatcher
    wa, wb = set(re.findall(r"[a-z]{4,}", a.lower())), set(re.findall(r"[a-z]{4,}", b.lower()))
    overlap = len(wa & wb) / max(1, min(len(wa), len(wb)))
    return overlap >= 0.67 or SequenceMatcher(None, a.lower(), b.lower()).ratio() >= 0.8


def _avg(xs):
    xs = [x for x in xs if x is not None]
    return round(sum(xs) / len(xs), 1) if xs else None


def report_metrics(session) -> dict:
    answered = [q for q in session.questions if q.answer]
    scored = [q for q in answered if q.answer.scores]
    s = lambda q, k: (q.answer.scores or {}).get(k)  # noqa: E731
    d = lambda q: q.answer.details or {}  # noqa: E731

    tech = [q for q in scored if q.question_type in TECHNICAL_TYPES]
    dimensions = {
        # knowledge: correctness + completeness, technical/project questions only
        "technical_knowledge": _avg([((s(q, "correctness") or 0) + (d(q).get("completeness") or s(q, "correctness") or 0))
                                     / 2 * 10 for q in tech]),
        "relevance": _avg([s(q, "relevance") * 10 for q in scored if s(q, "relevance") is not None]),
        "answer_structure": _avg([s(q, "clarity") * 10 for q in scored if s(q, "clarity") is not None]),
        "communication_clarity": _avg([s(q, "communication") * 10 for q in scored if s(q, "communication") is not None]),
    }

    words = [len(q.answer.text.split()) for q in answered]
    voice = [q for q in answered if q.answer.input_mode == "voice"]
    paces = []
    for q in voice:
        secs = (d(q).get("observed") or {}).get("speech_seconds")
        if secs and secs >= 3:
            paces.append(len(q.answer.text.split()) / secs * 60)
    filler_count = sum(len(FILLERS.findall(q.answer.text)) for q in voice)
    voice_words = sum(len(q.answer.text.split()) for q in voice)
    indicators = {
        "answers": len(answered),
        "avg_words_per_answer": _avg(words),
        "avg_seconds_to_answer": _avg([q.answer.response_seconds for q in answered]),
        "spoken_answers": len(voice),
        "speaking_pace_wpm": _avg(paces),
        "filler_words_per_100": round(filler_count / voice_words * 100, 1) if voice_words >= 30 else None,
        "very_short_answers": sum(1 for w in words if w < 8),
        "stopped_at_time_limit": sum(1 for q in answered if (d(q).get("observed") or {}).get("interrupted")),
        "limitations": INDICATOR_LIMITS,
    }

    topics = []
    for q in sorted(scored, key=lambda q: q.answer.score or 0):  # weakest answers first
        for c in d(q).get("missing_concepts") or []:
            if not any(_near(c, t) for t in topics):
                topics.append(c)

    overall = session.overall_score
    level = ai.next_difficulty(session.difficulty or "medium", overall)
    if overall is None:
        who, why = session.interviewer or interviewers.DEFAULT, "Not enough evaluated answers yet."
    elif overall < 50:
        who, why = "aria", "Rebuild confidence and fundamentals with supportive practice first."
    elif overall < 75:
        who, why = ("elena" if session.category in ("hr", "behavioral") else "victor",
                    "Work on depth and specific examples with a more demanding interviewer.")
    else:
        who, why = "marcus", "You are ready for pressure: practise staying clear and concise under time limits."
    return {
        "dimensions": dimensions,
        "question_scores": [{"position": q.position, "type": q.question_type, "score": q.answer.score}
                            for q in answered],
        "indicators": indicators,
        "suggested_topics": topics[:8],
        "recommended_next": {"difficulty": level, "interviewer": who, "reason": why},
    }
